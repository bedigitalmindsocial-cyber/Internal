"""Write one brief file per page (packs/NN-id.md) with everything a page agent needs, in one read:
page card and journey neighbours, the mandatory question sets that apply, the compliance blocks for its
flags (verbatim), site values, site memory, the pattern library, and pointers to golden/neighbour memories.

Usage: python3 scripts/pack.py NN [NN ...]   or   --all
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)
read = lambda p: open(p, encoding="utf-8").read() if os.path.exists(p) else ""


def question_sets(p):
    keys = ["every_page"]
    t, f, u = p["template"], p["flags"], p["url"]
    if u.startswith("/open-account/") or u == "/lp/open-account":
        keys.append("account_opening")
    if "fo_risk" in f and t != "G":
        keys.append("trading_fo")
    if "mf_risk" in f or "distributor_disclaimer" in f and p["entity"] == "Wealth":
        keys.append("mutual_funds")
    if t == "C":
        keys.append("calculator")
    if t == "P":
        keys.append("partner")
    if "pms" in f:
        keys.append("pms")
    if "coming_soon" in f:
        keys.append("coming_soon")
    if t == "G":
        keys.append("legal")
    if t == "B":
        keys.append("data")
    if t == "F":
        keys.append("company")
    return keys


def compliance_blocks(flags):
    doc = read(P("rules", "compliance-blocks.md"))
    out = []
    for part in re.split(r"\n(?=## )", doc):
        m = re.match(r"## (\w+)", part)
        if m and (m.group(1) in flags or m.group(1) == "regulated_numbers"):
            out.append(part.strip())
    return "\n\n".join(out)


def card(p):
    return (f'{p["file"][:-5]} · "{p["title"]}" · {p["url"]} · template {p["template"]} · {p["mode"]}'
            + (f' (inherits {p["golden_file"]})' if p.get("golden_file") else "")
            + f' · entity {p["entity"]} · phase {p["phase"]}')


def pack(p, sm):
    by_url = {x["url"]: x for x in sm["pages"]}
    qs = json.load(open(P("rules", "question-sets.json"), encoding="utf-8"))
    values = {k: v for k, v in json.load(open(P("memory", "values.json"), encoding="utf-8")).items() if not k.startswith("_")}
    parent = by_url.get(p.get("parent") or "")
    children = [x for x in sm["pages"] if x.get("parent") == p["url"]]
    siblings = [x for x in sm["pages"] if p.get("parent") and x.get("parent") == p["parent"] and x["url"] != p["url"]]
    by_file = {x["file"]: x for x in sm["pages"]}
    mems = []
    for x in ([parent] if parent else []) + children + ([by_file[p["golden_file"]]] if p.get("golden_file") else []):
        mp = P("memory", "pages", x["file"][:-5] + ".md")
        if os.path.exists(mp):
            mems.append(f'- memory/pages/{x["file"][:-5]}.md ({x["title"]})')
    lines = [
        f"# Brief for {p['file'][:-5]}: {p['title']}",
        "", "Generated by scripts/pack.py. Read this first; open other files only when this points to them.", "",
        "## The page",
        f"- {card(p)}",
        f"- Template {p['template']}: {sm['templates'][p['template']]}",
        f"- Audiences: {', '.join(p['audiences'])} (codes in context/facts.md section 3)",
        f"- Primary action: \"{p['primary_cta']}\" -> {p['cta']['href']} · event {p['cta']['event']}"
        + (f" · form data goes to {p['cta']['form_entity']}" if p['cta'].get('form_entity') else ""),
        f"- Flags: {', '.join(p['flags']) or 'none'}",
        f"- Parent hub: {card(parent) if parent else 'none (top level)'}",
        f"- Children: {'; '.join(c['title'] + ' ' + c['url'] for c in children) or 'none'}",
        f"- Siblings: {'; '.join(s['title'] + ' ' + s['url'] for s in siblings[:12]) or 'none'}",
        "", "## Mandatory questions for this page type (answer all, plus 3+ page-specific ones with a source)",
    ]
    for k in question_sets(p):
        lines.append(f"**{k.replace('_', ' ')}**")
        lines += [f"- {q}" for q in qs[k]]
    extra = (["partner"] if p["template"] == "P" else []) + (["proprietary"] if p["entity"] == "Capital" and p["template"] in ("A", "D", "F") else [])
    lines += ["", "## Compliance blocks for this page's flags (verbatim)", compliance_blocks(p["flags"] + extra) or "none",
              "", "## Site values (use {{key}} tokens; null = shows a placeholder chip)"]
    for k, v in values.items():
        lines.append(f"- `{{{{{k}}}}}` = {v['value'] if v['value'] is not None else 'NOT KNOWN: ' + v['label']} ({v['status']})")
    lines += ["", "## Site memory (decisions for every page)", read(P("memory", "site.md")).split("\n", 2)[-1].strip(),
              "", "## Pattern library", read(P("memory", "patterns.md")).split("\n", 2)[-1].strip()]
    comp = read(P("theme", "components.md"))
    if comp:
        lines += ["", "## Component markup library (theme/components.html)", comp.strip()]
    lines += ["", "## Other memories worth reading", "\n".join(mems) or "- none yet",
              "", "## Reference files", "- rules/page-method.md (method), rules/figma-html.md (HTML rules), rules/voice-and-claims.md, rules/claims.json",
              "- context/facts.md (business), context/decisions.md, context/compliance.md, context/placeholders.md, context/motilal-patterns.md",
              "- theme/sections-reference.html (theme markup, copy class names from here), theme/patterns.css",
              f"- craft checklists: private/design-skills/.claude/skills/better-layout/SKILL.md, impeccable/reference/layout.md, polish.md, clarify.md, mode-persuade.md (the ROOT theme and rules win on any conflict)"]
    os.makedirs(P("packs"), exist_ok=True)
    open(P("packs", p["file"][:-5] + ".md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")


def main(argv):
    sm = json.load(open(P("sitemap.json"), encoding="utf-8"))
    want = set(argv)
    n = 0
    for p in sm["pages"]:
        if "--all" in want or f'{p["n"]:02d}' in want or p["id"] in want:
            pack(p, sm)
            n += 1
    print(f"wrote {n} brief(s) to packs/")
    return 0 if n else 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

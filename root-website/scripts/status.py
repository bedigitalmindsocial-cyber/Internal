"""One table of where every page stands, read from the files (so any session can resume).

Per page: source written, built, lint state, overflow, page-memory status. Writes STATUS.md.
Usage: python3 scripts/status.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)


def mem_status(name):
    path = P("memory", "pages", name + ".md")
    if not os.path.exists(path):
        return "-"
    m = re.search(r"^status:\s*(\S+)", open(path, encoding="utf-8").read(), re.M)
    return m.group(1) if m else "?"


def main():
    sm = json.load(open(P("sitemap.json"), encoding="utf-8"))
    rows, counts = [], {}
    for p in sm["pages"]:
        name = p["file"][:-5]
        lint = P("review", name, "lint.json")
        shots = P("review", name, "shots.json")
        lt = "-"
        if os.path.exists(lint):
            r = json.load(open(lint))
            lt = "fail" if r["errors"] else ("review" if r["reviews"] else "pass")
        ov = "-"
        if os.path.exists(shots):
            s = json.load(open(shots))
            ov = "OVERFLOW" if s["desktop"]["overflow"] or s["mobile"]["overflow"] else "ok"
        st = mem_status(name)
        counts[st] = counts.get(st, 0) + 1
        rows.append(f'| {p["n"]:02d} | {p["title"]} | {p["template"]} | {p["phase"]} | {p["mode"]} | '
                    f'{"y" if os.path.exists(P("pages", "src", p["file"])) else "-"} | '
                    f'{"y" if os.path.exists(P("figma", p["file"])) else "-"} | {lt} | {ov} | {st} |')
    out = ("# Build status\n\nGenerated by scripts/status.py from the files on disk.\n\n"
           + " · ".join(f"{k}: {v}" for k, v in sorted(counts.items())) + "\n\n"
           "| # | Page | Tpl | Phase | Mode | Src | Built | Lint | Layout | Memory status |\n|---|---|---|---|---|---|---|---|---|---|\n"
           + "\n".join(rows) + "\n")
    open(P("STATUS.md"), "w", encoding="utf-8").write(out)
    print(" · ".join(f"{k}: {v}" for k, v in sorted(counts.items())))


if __name__ == "__main__":
    main()

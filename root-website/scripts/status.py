"""Where every page stands, read only from files, so any session can resume.

Per page: source, build, gate (lint + layout), reviewer verdict, memory status, whether the checks are stale
(the built file changed after it was linted, shot or reviewed), and the NEXT stage:
  brief -> judge (golden only) -> build -> fix (gate failed) -> review -> fix (reviewer asked) -> done
Writes STATUS.md. Usage: python3 scripts/status.py [--json]
"""
import hashlib, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)


def jload(path):
    try:
        return json.load(open(path))
    except Exception:
        return None


def page_state(p):
    name = p["file"][:-5]
    mem = P("memory", "pages", name + ".md")
    mtxt = open(mem, encoding="utf-8").read() if os.path.exists(mem) else ""
    mstat = (re.search(r"^status:\s*(\S+)", mtxt, re.M) or [None, "-"])[1] if mtxt else "-"
    judged = "Judge " in mtxt
    src = os.path.exists(P("pages", "src", p["file"]))
    built = P("figma", p["file"])
    sha = hashlib.sha1(open(built, "rb").read()).hexdigest()[:12] if os.path.exists(built) else None
    gate = jload(P("review", name, "gate.json"))
    verdict = jload(P("review", name, "verdict.json"))
    stale = bool(sha) and any(x and x.get("sha") and x["sha"] != sha for x in (gate, verdict))
    if not mtxt:
        nxt = "brief"
    elif p["mode"] == "golden" and not judged:
        nxt = "judge"
    elif not src or not sha:
        nxt = "build"
    elif not gate or stale and (not gate or gate.get("sha") != sha):
        nxt = "gate"
    elif not gate.get("ok"):
        nxt = "fix (gate)"
    elif not verdict or verdict.get("sha") != sha:
        nxt = "review"
    elif verdict["verdict"] == "fix":
        nxt = "fix (review)"
    else:
        nxt = "done" if mstat != "approved" else "approved"
    return {"page": name, "n": p["n"], "title": p["title"], "template": p["template"], "phase": p["phase"], "mode": p["mode"],
            "memory": mstat, "src": src, "built": bool(sha), "gate": None if not gate else gate.get("ok"),
            "verdict": verdict and verdict["verdict"], "score": verdict and verdict.get("score"), "stale": stale, "next": nxt}


def main(argv):
    sm = json.load(open(P("sitemap.json"), encoding="utf-8"))
    rows = [page_state(p) for p in sm["pages"]]
    if "--json" in argv:
        print(json.dumps(rows, indent=1))
        return 0
    counts = {}
    for r in rows:
        counts[r["next"]] = counts.get(r["next"], 0) + 1
    summary = " · ".join(f"{k}: {v}" for k, v in sorted(counts.items(), key=lambda kv: -kv[1]))
    fmt = lambda v: "-" if v is None else ("y" if v is True else ("n" if v is False else str(v)))
    out = ["# Build status", "", "Generated by scripts/status.py from the files on disk. Next stage per page:", "", summary, "",
           "| # | Page | Tpl | Ph | Mode | Memory | Src | Built | Gate ok | Verdict | Score | Stale | Next |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f'| {r["n"]:02d} | {r["title"]} | {r["template"]} | {r["phase"]} | {r["mode"]} | {r["memory"]} | {fmt(r["src"])} | '
                   f'{fmt(r["built"])} | {fmt(r["gate"])} | {fmt(r["verdict"])} | {fmt(r["score"])} | {"STALE" if r["stale"] else ""} | {r["next"]} |')
    open(P("STATUS.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(summary)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

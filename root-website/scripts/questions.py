"""Collect open questions from every page memory (section 10) into memory/questions.md, deduplicated.

Questions that the orchestrator has moved to the "## Answered" section of questions.md are kept and are not
re-listed as open. Run after every wave so the questions survive even if the session dies.
Usage: python3 scripts/questions.py
"""
import glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)
norm = lambda q: re.sub(r"[^a-z0-9 ]", "", q.lower()).strip()


def main():
    path = P("memory", "questions.md")
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    answered = old.split("## Answered", 1)[1] if "## Answered" in old else "\n| Question | Answer | Date | Applied to |\n|---|---|---|---|\n"
    done = {norm(r.split("|")[1]) for r in answered.splitlines() if r.startswith("|") and not r.startswith("|---") and "Question" not in r}
    rows = {}
    for mem in sorted(glob.glob(P("memory", "pages", "[0-9][0-9]-*.md"))):
        page = os.path.basename(mem)[:-3]
        md = open(mem, encoding="utf-8").read()
        m = re.search(r"## 10\..*?\n(.*?)(\n## |\Z)", md, re.S)
        if not m:
            continue
        for r in m.group(1).splitlines():
            if not r.startswith("|") or r.startswith("|---") or "Why it matters" in r:
                continue
            cells = [c.strip() for c in r.strip("|").split("|")]
            if len(cells) < 4 or not cells[0] or norm(cells[0]) in done:
                continue
            key = norm(cells[0])[:80]
            if key in rows:
                rows[key]["pages"].append(page)
            else:
                rows[key] = {"q": cells[0], "why": cells[1], "default": cells[2], "owner": cells[3], "pages": [page]}
    lines = ["# Open questions for Aikyam and Giraffe", "",
             "Generated by scripts/questions.py from page memories (section 10). Pages never wait: each uses the default shown",
             "and a visible placeholder. The orchestrator asks the user the highest-impact ones at each gate and moves the",
             "answers to the Answered section below (then updates memory/values.json or memory/site.md and rebuilds).", "",
             f"## Open ({len(rows)})", "", "| # | Question | Why it matters | Default used meanwhile | Owner | Raised by |", "|---|---|---|---|---|---|"]
    for i, r in enumerate(sorted(rows.values(), key=lambda r: (-len(r["pages"]), r["owner"])), 1):
        lines.append(f'| {i} | {r["q"]} | {r["why"]} | {r["default"]} | {r["owner"]} | {", ".join(r["pages"][:6])}{" +" + str(len(r["pages"]) - 6) if len(r["pages"]) > 6 else ""} |')
    open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n\n## Answered" + answered.rstrip() + "\n")
    print(f"{len(rows)} open question(s)")


if __name__ == "__main__":
    main()
